// Runs after `vite build`: writes dist/sw.js, a service worker that caches every built file
// so the app opens offline. The cache name is a hash of the build, so each deploy replaces it.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const dist = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'dist');
const files = [];
(function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full);
    else files.push(path.relative(dist, full).split(path.sep).join('/'));
  }
})(dist);

const assets = files.filter(f => f !== 'sw.js' && !f.endsWith('.map'));
const hash = crypto.createHash('sha256');
for (const f of assets.sort()) hash.update(f).update(fs.readFileSync(path.join(dist, f)));
const version = 'lean-bulk-' + hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs
const VERSION = ${JSON.stringify(version)};
const ASSETS = ${JSON.stringify(['./', ...assets])};

self.addEventListener('install', e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('./').then(r => r || caches.match('index.html'))));
    return;
  }
  e.respondWith(caches.match(req).then(r => r || fetch(req)));
});
`;
fs.writeFileSync(path.join(dist, 'sw.js'), sw);
fs.writeFileSync(path.join(dist, '.nojekyll'), '');
console.log(`sw.js: ${assets.length} files cached as ${version}`);
